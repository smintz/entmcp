// ToolManifest is the JSON manifest written when SpecPath is configured.
type ToolManifest struct {
	Tools []ToolManifestEntry `json:"tools"`
}

// ToolManifestEntry describes one tool in the manifest.
type ToolManifestEntry struct {
	Name        string `json:"name"`
	Description string `json:"description,omitempty"`
}

// writeSpecManifest writes a JSON manifest of all generated tools.
func writeSpecManifest(specs []ToolSpec, cfg *Config) error {
	manifest := ToolManifest{}
	for _, spec := range specs {
		manifest.Tools = append(manifest.Tools, toolManifestEntries(spec)...)
	}
	b, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return err
	}
	dir := filepath.Dir(cfg.SpecPath)
	if err := os.MkdirAll(dir, 0755); err != nil {
		return err
	}
	return os.WriteFile(cfg.SpecPath, b, 0644)
}

func toolManifestEntries(spec ToolSpec) []ToolManifestEntry {
	var entries []ToolManifestEntry
	if spec.Ops.Has(OpCreate) {
		entries = append(entries, ToolManifestEntry{Name: spec.CreateToolName, Description: "Create a new " + spec.TypeName})
	}
	if spec.Ops.Has(OpRead) {
		entries = append(entries, ToolManifestEntry{Name: spec.GetToolName, Description: "Get a " + spec.TypeName + " by ID"})
	}
	if spec.Ops.Has(OpList) {
		entries = append(entries, ToolManifestEntry{Name: spec.ListToolName, Description: "List " + plural(spec.TypeName) + " with filtering, sorting and pagination"})
	}
	if spec.Ops.Has(OpUpdate) {
		entries = append(entries, ToolManifestEntry{Name: spec.UpdateToolName, Description: "Update a " + spec.TypeName + " by ID"})
	}
	if spec.Ops.Has(OpDelete) {
		entries = append(entries, ToolManifestEntry{Name: spec.DeleteToolName, Description: "Delete a " + spec.TypeName + " by ID"})
	}
	return entries
}
